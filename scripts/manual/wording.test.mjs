import test from 'node:test';
import assert from 'node:assert/strict';
import { fixHeading, fixWording } from './wording.mjs';

test('wording fixes keep case forms and capital letters', () => {
  assert.equal(fixWording('Снятие/установка комбинированного счетчика'), 'Снятие/установка щитка приборов');
  assert.equal(fixWording('Комбинированный счетчик неисправен'), 'Щиток приборов неисправен');
  assert.equal(fixWording('Замените катушку IG, связанную с кодом'), 'Замените катушку зажигания, связанную с кодом');
  assert.equal(fixWording('Перед установкой скользящего штифта на кронштейн'), 'Перед установкой направляющего пальца на кронштейн');
  assert.equal(fixWording('Ошибка системы датчика угла поворота кулачка IN'), 'Ошибка системы датчика положения распредвала IN');
  assert.equal(fixWording('рядный 4-цилиндровый, 2-кулачковый, 4-клапанный'), 'рядный 4-цилиндровый, DOHC, 4-клапанный');
  assert.equal(fixWording('Снимите модуль накачки сиденья водителя с рулевого колеса'), 'Снимите модуль подушки безопасности водителя с рулевого колеса');
  assert.equal(fixWording('Снятие/установка модуля накачки пассажирского сиденья'), 'Снятие/установка модуля подушки безопасности пассажира');
  assert.equal(fixWording('Проверка цепи модуля надува правой шторки'), 'Проверка цепи модуля правой шторки безопасности');
  assert.equal(fixWording('Неисправность системы надувания подушки безопасности водителя'), 'Неисправность цепи срабатывания подушки безопасности водителя');
  assert.equal(fixWording('храните неразвернутые модули накачивания и'), 'храните неразвернутые модули подушек безопасности и');
  assert.equal(fixWording('Детали диагноза'), 'Условие обнаружения');
  assert.equal(fixWording('Вы проводили «проверку системы управления двигателем»?？'), 'Вы проводили «проверку системы управления двигателем»?');
  assert.equal(fixWording('\nОсуществлять.\n'), '\n— выполните.\n');
  assert.equal(fixWording('при проведении экзамена по вождению может'), 'при проведении пробной поездки может');
  assert.equal(fixWording('Метод привода передача инфекции'), 'Метод привода трансмиссия');
  assert.equal(fixWording('\nтело\n'), '\nкузов\n');
  assert.equal(fixWording(' приостановка '), ' подвеска ');
  assert.equal(fixWording('83. тело земля Расположение клемм'), '83. масса кузова Расположение клемм');
  assert.equal(fixWording('Проверка двигателя стиральной машины'), 'Проверка двигателя омывателя');
  assert.equal(fixWording('стиральная машина не работает'), 'омыватель не работает');
  assert.equal(fixWording('замените SW стеклоочистителя и шайбы'), 'замените SW стеклоочистителя и омывателя');
  assert.equal(fixWording('играй, расслабься'), 'люфт, ослабление креплений');
  assert.equal(fixWording('Играйте в педаль и зазор между ней и половицей'), 'Свободный ход педали и зазор между ней и полом');
  assert.equal(fixWording('схватить'), 'сцепление');
});

test('wording fixes leave correct text alone', () => {
  for (const text of ['приводится в действие кулачком топливного насоса', 'высота кулачка', 'удаление текущих DTC', 'реле IG1', 'надувной подушки безопасности', 'ваше тело или одежда', 'стопорные шайбы', 'клей схватится', 'тело клапана', 'приостановка работы'])
    assert.equal(fixWording(text), text);
});

test('heading fixes apply only to whole headings', () => {
  assert.equal(fixHeading('\nУдаление\n'), 'Снятие');
  assert.equal(fixHeading('Разложение'), 'Разборка');
  assert.equal(fixHeading('Удаление воздуха'), null);
});
