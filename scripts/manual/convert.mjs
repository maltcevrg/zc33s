import { createHash } from 'node:crypto';
import { parseXmlStrict } from './xml.mjs';
import { fixHeading, fixWording } from './wording.mjs';
import { layoutCalsTable, layoutConditionDiag } from '../../src/features/manual/table.js';

const TAGS = new Set(`title ptxt emph sub sup servinfosub topic subtopic paragroup attention1 attention2 attention3 attention4
  s1 s2 s3 list1 list2 list3 item figure testfigure graphic callout callout-l spec table tgroup colspec thead tbody row entry
  diag testgroup question result action test1 condition ps intxref intxrefpoff intxreftitleoff1 intxreftitleoff
  torque torqueitem t-part t-part1 t-value1 t-note servicetool servicetoolitem s-part s-number
  materials materialitem m-part m-desc m-number m-name scantool scantool-title
  spec-sdm sdm-title sdm-part sdm-model sdm1 sdm2 sdm-condition sdm-value button symbol deflist term def`.split(/\s+/));
// Revision marks of the authoring system: suzuki.xsl has no template for them and prints nothing.
const EMPTY_MARKERS = new Set(['p-change','c-change']);
const ATTRS = new Set('id etype type refid graphicname width height cols colnum colname colwidth morerows namest nameend align valign num code name'.split(' '));
// Source counts compared after conversion; these elements carry the content a reader must not lose.
export const COUNTED_TAGS = Object.freeze(['graphic','table','testgroup','result','action','condition','ps','torqueitem','servicetoolitem','materialitem','attention1','attention2','attention3','attention4','intxref','intxrefpoff','intxreftitleoff','intxreftitleoff1']);
// Labels and units generated by the original suzuki.xsl / ui.xslt for UI_lang='ru'.
export const semanticLabels = Object.freeze({ attention1:'ПРЕДУПРЕЖДЕНИЕ:', attention2:'ВНИМАНИЕ:', attention3:'ПРИМЕЧАНИЕ:', attention4:'УВЕДОМЛЕНИЕ:', torque:'Момент затяжки', torqueUnit:'Нм', servicetool:'Специальный инструмент', condition:'Условие', ps:'Возможная причина', conditionAction:'Действие', step:'Шаг', testAction:'Действие', yes:'Да', no:'Нет' });

export function walkNodes(nodes, visit) {
  for (const node of nodes) if (typeof node !== 'string') { visit(node); walkNodes(node.children,visit); }
}
export function plainText(nodes) {
  return nodes.map(n=>typeof n==='string'?n:plainText(n.children)+(n.tag==='ptxt'||n.tag==='title'?'\n':'')).join('');
}
// Search text also carries the block labels the reader adds, so "момент затяжки свечи" finds the spark plug procedure.
const SEARCH_LABELS = Object.freeze({ torque:semanticLabels.torque, servicetool:semanticLabels.servicetool });
export function searchText(nodes) {
  return nodes.map(n=>typeof n==='string'?n:(SEARCH_LABELS[n.tag]?SEARCH_LABELS[n.tag]+' ':'')+searchText(n.children)+(n.tag==='ptxt'||n.tag==='title'?'\n':'')).join('');
}
export function countSourceElements(dom) {
  const info=dom.getElementsByTagName('servinfo')[0];
  return Object.fromEntries(COUNTED_TAGS.map(tag=>[tag,info.getElementsByTagName(tag).length]).filter(([,n])=>n));
}
// Section files list documents as <s i t>; auxiliary indexes (DTC, symptoms...) as <servinfo id title>.
export function buildTitleCatalog(docs) {
  const titles = new Map();
  const add=(id,title)=>{
    if(!id?.startsWith('AJPHSB0P')||!title) return;
    if(titles.has(id)&&titles.get(id)!==title) throw new Error(`Conflicting title: ${id}`);
    titles.set(id,title);
  };
  for (const doc of docs) {
    for(const node of doc.getElementsByTagName('s')) add(node.getAttribute('i'),node.getAttribute('t'));
    for(const node of doc.getElementsByTagName('servinfo')) if(!titles.has(node.getAttribute('id'))) add(node.getAttribute('id'),node.getAttribute('title'));
  }
  return titles;
}

export function convertDocument(xml,{entities,titles,availableIds,imagePaths,symbolPaths=new Map()}) {
  const dom=parseXmlStrict(xml,{entitySource:entities});
  const info=dom.getElementsByTagName('servinfo')[0];
  if(!info) throw new Error('No servinfo');
  const id=info.getAttribute('servinfosgmlid');
  if(!availableIds.has(id)) throw new Error(`Unexpected document: ${id}`);
  const titleNode=Array.from(info.childNodes).find(n=>n.nodeName==='title');
  const title=fixWording(titleNode.textContent.trim());
  const groupId=dom.getElementsByTagName('servinfotype')[0].getAttribute('sitcode');
  const anchors=[];const references=[];const images=[];const sameDocumentLabels=[];
  const convert = original => {
    if(original.nodeType===3||original.nodeType===4) return fixWording(original.data);
    if(original.nodeType===8) return null;
    if(original.nodeType!==1) throw new Error(`Unsupported XML node: ${original.nodeName}`);
    const tag=original.nodeName;
    if(EMPTY_MARKERS.has(tag)) {
      if(original.childNodes.length) throw new Error(`Unexpected content in ${tag} in ${id}`);
      return null;
    }
    if(tag==='img') {
      if(!original.parentNode.nodeName.startsWith('intxref')) throw new Error(`Unexpected source img in ${id}`);
      return null;
    }
    if(!TAGS.has(tag)) throw new Error(`Unknown significant element: ${tag} in ${id}`);
    const attrs={};
    for(const attr of original.attributes) if(ATTRS.has(attr.name)) attrs[attr.name]=attr.value;
    if(attrs.id) {if(anchors.includes(attrs.id))throw new Error(`Duplicate anchor: ${attrs.id} in ${id}`);anchors.push(attrs.id);}
    let children=Array.from(original.childNodes).map(convert).filter(n=>n!==null);
    // The XSL prints sub/sup with normalize-space(); scantool-title prints only its own text nodes.
    if(tag==='sub'||tag==='sup') children=[plainText(children).replace(/\s+/g,' ').trim()];
    if(tag==='scantool-title'&&children.some(n=>typeof n!=='string'&&n.tag!=='emph')) throw new Error(`Unexpected scantool-title content in ${id}`);
    if(tag==='t-value1') children.push(' '+semanticLabels.torqueUnit);
    if(tag==='title'){const heading=fixHeading(plainText(children));if(heading)children=[heading];}
    // suzuki.xsl pairs each term with the def that follows it; any other layout would be lost by the XSL.
    if(tag==='deflist'){
      const elements=children.filter(n=>typeof n!=='string');
      if(children.some(n=>typeof n==='string'&&n.trim())||elements.length%2||elements.some((n,i)=>n.tag!==(i%2?'def':'term')))throw new Error(`Unexpected deflist structure in ${id}`);
    }
    if(tag==='graphic') {
      const path=imagePaths.get(attrs.graphicname);
      if(!path) throw new Error(`Missing image: ${attrs.graphicname} in ${id}`);
      attrs.path=path;
      images.push({sourceName:attrs.graphicname,path,width:attrs.width,height:attrs.height});
    }
    // suzuki.xsl: type="chara" symbols are text marks; all others are pictograms from Xml/symbol/<name>.png.
    if(tag==='symbol'&&attrs.type!=='chara'){
      const path=symbolPaths.get(attrs.name);
      if(!path) throw new Error(`Missing symbol: ${attrs.name} in ${id}`);
      attrs.path=path;
    }
    let pendingTitle=null;
    if(tag.startsWith('intxref')) {
      let [targetId,anchor='',extra]=(attrs.refid||'').split('#');
      // A bare subsection ID (document ID + 3 digits) points at a block, usually in the same document.
      if(!anchor&&!titles.has(targetId)&&/^AJPHSB0P\w{7}\d{3}$/.test(targetId)){anchor=targetId;targetId=targetId.slice(0,15);}
      if(extra!==undefined||!titles.has(targetId)) throw new Error(`Unresolved reference: ${attrs.refid} in ${id}`);
      const reference={targetId,anchor,title:fixWording(titles.get(targetId)),available:availableIds.has(targetId)};
      references.push(reference);
      attrs.refid=anchor?`${targetId}#${anchor}`:targetId;
      attrs.targetTitle=reference.title;attrs.available=reference.available;
      if(!plainText(children).trim()){
        if(targetId===id&&anchor)pendingTitle={reference,anchor};
        else children.push(reference.title);
      }
    }
    const node={tag,attrs,children};
    if(pendingTitle)sameDocumentLabels.push({node,...pendingTitle});
    if(tag==='tgroup')layoutCalsTable(node);
    if(tag==='diag'&&attrs.type==='condition')layoutConditionDiag(node);
    return node;
  };
  const body=Array.from(info.childNodes).filter(n=>n!==titleNode).map(convert).filter(n=>n!==null);
  if(sameDocumentLabels.length){
    const blocks=new Map();walkNodes(body,n=>{if(n.attrs.id)blocks.set(n.attrs.id,n);});
    for(const {node,reference,anchor} of sameDocumentLabels){
      const block=blocks.get(anchor);
      if(!block)throw new Error(`Missing reference anchor: ${anchor} in ${id}`);
      const heading=block.children.find(n=>n.tag==='title');
      const label=heading?plainText(heading.children).replace(/\s+/g,' ').trim():reference.title;
      node.children.push(label);node.attrs.targetTitle=label;
    }
  }
  return {schemaVersion:1,id,title,groupId,body,anchors,images,references,sourceCounts:countSourceElements(dom),searchText:searchText(body).replace(/\s+/g,' ').trim(),sourceSha256:createHash('sha256').update(xml).digest('hex')};
}
